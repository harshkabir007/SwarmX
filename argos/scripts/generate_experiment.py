#!/usr/bin/env python3
"""Generate an ARGoS3 experiment (arena + map) from the shared SwarmX warehouse model.

    python3 scripts/generate_experiment.py --robots 50 --aisles 20 --tasks 150 --mode swarmx
    argos3 -c experiments/swarmx_50r_20a_swarmx_s1.argos

Foot-bots are 17 cm in diameter, so the warehouse is scaled to --cell metres per
grid cell (default 0.35 m: single-lane aisles leave ~9 cm clearance per side).
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "ros2_ws", "src", "swarmx_core"))
from swarmx_core.warehouse import FREE, SHELF, Warehouse  # noqa: E402


def write_map(wh: Warehouse, cell: float, path: str) -> None:
    sym = {FREE: ".", SHELF: "#"}
    with open(path, "w") as f:
        f.write(f"map {wh.width} {wh.height} {cell}\n")
        for y in range(wh.height):
            f.write("".join(sym.get(wh.grid[y][x], "X") for x in range(wh.width)) + "\n")
        zones = sorted(wh.zones.values(), key=lambda z: z.zid)
        f.write(f"zones {len(zones)}\n")
        for z in zones:
            ys = [c[1] for c in z.cells]
            f.write(f"{z.cells[0][0]} {min(ys)} {max(ys)}\n")
        for name, cells in (("pickups", wh.pickups), ("dropoffs", wh.dropoffs), ("depot", wh.depot)):
            f.write(f"{name} {len(cells)}\n")
            for c in cells:
                f.write(f"{c[0]} {c[1]}\n")


def start_cells(wh: Warehouse, n: int):
    """Spread robots over the open areas and cross aisles, away from aisle mouths."""
    mouths = {c for z in wh.zones.values() for c in z.ends.values()}
    cand = [(x, y) for y in range(1, wh.height - 1) for x in range(1, wh.width - 1)
            if wh.is_free((x, y)) and wh.zone_of((x, y)) is None and (x, y) not in mouths
            and (x, y) not in wh.dropoffs and (x, y) not in wh.chargers]
    # every other cell so robots start 2 cells apart
    cand = [c for c in cand if (c[0] + c[1]) % 2 == 0]
    if n > len(cand):
        raise SystemExit(f"only {len(cand)} start cells for {n} robots - use more aisles")
    step = len(cand) / n
    return [cand[int(i * step)] for i in range(n)]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--robots", type=int, default=30)
    ap.add_argument("--aisles", type=int, default=12)
    ap.add_argument("--tasks", type=int, default=90)
    ap.add_argument("--mode", choices=["swarmx", "stopwait"], default="swarmx")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--cell", type=float, default=0.35)
    ap.add_argument("--length", type=int, default=3000, help="max experiment length [s]")
    ap.add_argument("--rab-range", type=float, default=2.5, help="radio range [m]")
    ap.add_argument("--visual", action="store_true", help="add the Qt/OpenGL visualisation")
    ap.add_argument("--out", default=os.path.join(HERE, "..", "experiments"))
    args = ap.parse_args()

    wh = Warehouse(n_aisles=args.aisles)
    c = args.cell
    os.makedirs(args.out, exist_ok=True)
    tag = f"swarmx_{args.robots}r_{args.aisles}a_{args.mode}_s{args.seed}"
    map_path = os.path.abspath(os.path.join(args.out, f"map_{args.aisles}a.txt"))
    write_map(wh, c, map_path)
    boxes = []
    for i, (x0, y0, x1, y1, kind) in enumerate(wh._merged_boxes()):
        sx, sy = (x1 - x0) * c, (y1 - y0) * c
        boxes.append(f'    <box id="{"shelf" if kind == SHELF else "wall"}_{i}" size="{sx:.3f},{sy:.3f},0.4" movable="false">'
                     f'<body position="{x0 * c + sx / 2:.3f},{y0 * c + sy / 2:.3f},0" orientation="0,0,0"/></box>')
    bots = []
    for i, (x, y) in enumerate(start_cells(wh, args.robots)):
        bots.append(f'    <foot-bot id="fb{i}" rab_range="{args.rab_range}" rab_data_size="32">'
                    f'<body position="{(x + 0.5) * c:.3f},{(y + 0.5) * c:.3f},0" orientation="0,0,0"/>'
                    f'<controller config="swarmx"/></foot-bot>')
    build = os.path.abspath(os.path.join(HERE, "..", "build"))
    result = os.path.abspath(os.path.join(HERE, "..", "results", f"{tag}.json"))
    os.makedirs(os.path.dirname(result), exist_ok=True)
    W, H = wh.width * c, wh.height * c
    vis = ('  <visualization><qt-opengl><camera><placements><placement index="0" '
           f'position="{W / 2},{H / 2},{max(W, H)}" look_at="{W / 2},{H / 2},0" up="0,1,0" lens_focal_length="30"/>'
           '</placements></camera></qt-opengl></visualization>') if args.visual else "  <visualization/>"
    xml = f"""<?xml version="1.0" ?>
<!-- Generated by argos/scripts/generate_experiment.py from swarmx_core.warehouse -->
<argos-configuration>
  <framework>
    <system threads="0"/>
    <experiment length="{args.length}" ticks_per_second="10" random_seed="{args.seed}"/>
  </framework>
  <controllers>
    <swarmx_footbot_controller id="swarmx" library="{build}/libswarmx_footbot">
      <actuators>
        <differential_steering implementation="default"/>
        <range_and_bearing implementation="default"/>
        <leds implementation="default" medium="leds"/>
      </actuators>
      <sensors>
        <positioning implementation="default"/>
        <range_and_bearing implementation="medium" medium="rab" show_rays="false" noise_std_dev="0.0" packet_drop_prob="0.02"/>
      </sensors>
      <params map="{map_path}" mode="{args.mode}" max_speed="0.25"/>
    </swarmx_footbot_controller>
  </controllers>
  <loop_functions library="{build}/libswarmx_loop_functions" label="swarmx_loop_functions">
    <swarmx map="{map_path}" tasks="{args.tasks}" seed="{args.seed}" mode="{args.mode}" output="{result}"/>
  </loop_functions>
  <arena size="{W + 1:.2f},{H + 1:.2f},1" center="{W / 2:.2f},{H / 2:.2f},0.5">
{chr(10).join(boxes)}
{chr(10).join(bots)}
  </arena>
  <physics_engines><dynamics2d id="dyn2d"/></physics_engines>
  <media>
    <range_and_bearing id="rab" check_occlusions="true"/>
    <led id="leds"/>
  </media>
{vis}
</argos-configuration>
"""
    path = os.path.join(args.out, f"{tag}.argos")
    with open(path, "w") as f:
        f.write(xml)
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
